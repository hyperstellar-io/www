// Turns content/posts/*.json (written by /admin, one file per post) into lib/blogs/generated.ts, so posts stay plain imports on server and client.
// Runs before `dev` and `build`. Posts dated in the future are left out until a later build (see .github/workflows/scheduled-posts.yml).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../content/posts/", import.meta.url);
const all = readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .map((f) => {
    const p = JSON.parse(readFileSync(new URL(f, dir), "utf8"));
    for (const k of ["slug", "title", "dek", "kind", "published", "tag"]) if (!p[k]) throw new Error(`content/posts/${f}: missing "${k}"`);
    if (!Array.isArray(p.body) || !p.body.length) throw new Error(`content/posts/${f}: body must be a non-empty array`);
    if (Number.isNaN(+new Date(p.published))) throw new Error(`content/posts/${f}: bad "published" date`);
    return p;
  });
const now = Date.now();
const posts = all.filter((p) => +new Date(p.published) <= now);
writeFileSync(new URL("../lib/blogs/generated.ts", import.meta.url), `// Generated by scripts/build-posts.mjs from content/posts/*.json. Do not edit.\nimport type { Post } from "./types";\n\nexport const posts: Post[] = ${JSON.stringify(posts, null, 2)};\n`);
console.log(`build-posts: ${posts.length} post(s), ${all.length - posts.length} scheduled`);
